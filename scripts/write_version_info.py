"""Generate deterministic Windows PE version resources for Zadoo executables."""
from __future__ import annotations

import argparse
import re
from pathlib import Path

VERSION_PATTERN = re.compile(r"(?:0|[1-9][0-9]*)\.(?:0|[1-9][0-9]*)\.(?:0|[1-9][0-9]*)")
EXECUTABLES = ("Zadoo.exe", "Zadoo-x64.exe")


def render_version_info(version: str, filename: str) -> str:
    if not VERSION_PATTERN.fullmatch(version):
        raise ValueError("Version must contain exactly three non-negative integers without leading zeros.")
    parts = tuple(int(part) for part in version.split("."))
    if any(part > 65535 for part in parts):
        raise ValueError("Windows version components must be between 0 and 65535.")
    if filename not in EXECUTABLES:
        raise ValueError("Original filename must be Zadoo.exe or Zadoo-x64.exe.")
    numeric = (*parts, 0)
    strings = {
        "CompanyName": "Zadoo",
        "FileDescription": "Zadoo Windows remote-access host",
        "FileVersion": version,
        "InternalName": filename.removesuffix(".exe"),
        "LegalCopyright": "Copyright 2026 DIVYANSH-675 and Zadoo contributors",
        "OriginalFilename": filename,
        "ProductName": "Zadoo",
        "ProductVersion": version,
    }
    entries = ",\n".join(f"                StringStruct({key!r}, {value!r})" for key, value in strings.items())
    return f"""# Generated by scripts/write_version_info.py; do not edit.
VSVersionInfo(
    ffi=FixedFileInfo(
        filevers={numeric!r}, prodvers={numeric!r}, mask=0x3f,
        flags=0x0, OS=0x40004, fileType=0x1, subtype=0x0, date=(0, 0)
    ),
    kids=[
        StringFileInfo([
            StringTable('040904B0', [
{entries}
            ])
        ]),
        VarFileInfo([VarStruct('Translation', [1033, 1200])])
    ]
)
"""


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--version", required=True)
    parser.add_argument("--filename", required=True, choices=EXECUTABLES)
    parser.add_argument("--output", required=True, type=Path)
    args = parser.parse_args()
    resource = render_version_info(args.version, args.filename)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(resource, encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
